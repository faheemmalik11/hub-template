-- 0090_imported_messages_content_anchor — fix the pipeline's cross-channel/moved-file
-- relink check, which has been silently inert.
--
-- THE BUG: imported_messages.content_hash (migration 0033) stores the PROVIDER-NATIVE
-- hash (Drive's md5Checksum / Dropbox's block-based content_hash) — cheap, metadata-only,
-- exactly right for "did this Drive/Dropbox file change since I last saw THIS location"
-- (adapters/repo/receipts.py's content_changed_in_place()). known_content() reused that
-- same column for a DIFFERENT question — "has this exact CONTENT already been stored,
-- regardless of location/channel" — comparing it against roh.externe_id, which for a
-- scan-folder item is always a real "sha256:<hex>" anchor (adapters/source/google_drive
-- and dropbox_folder's content_anchor()). An md5/Dropbox-block hash can never equal a
-- SHA-256 hex digest, so known_content() never matched anything.
--
-- content_anchor stores that real SHA-256 anchor instead, populated only where it is
-- genuinely available (scan-folder items, after download) — additive, nullable, existing
-- rows get NULL, which known_content() already treats as "nothing to compare against".
alter table imported_messages add column if not exists content_anchor text;
