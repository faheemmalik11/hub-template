// Rebuilds supabase/migrations/00000000000000_schema.sql from supabase/schema/*.sql.
// The numbered files are the source a person reads; the baseline is what the CLI applies.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const schemaDir = "supabase/schema";
const target = "supabase/migrations/00000000000000_schema.sql";

const parts = readdirSync(schemaDir)
  .filter((name) => /^0\d+_.*\.sql$/.test(name))
  .sort();

const header = `-- The schema, as one migration.
--
-- GENERATED from supabase/schema/*.sql by scripts/build-baseline.mjs. Do not edit this file: edit
-- the numbered file the change belongs to and run the script again.
--
-- Everything a new client's database needs, in order, with no history. The 248 migrations of the
-- Hub this template came from are not carried: they never described their own result, and the
-- questions only they answered are answered by this repository's own history.
--
-- The catalogue of pages and roles is NOT here. It is project data, in supabase/catalogue.sql,
-- applied after this file and replaced wholesale by each client.

`;

const body = parts
  .map((name) => {
    const text = readFileSync(join(schemaDir, name), "utf8");
    return `-- ===================================================================== ${name}\n\n${text}`;
  })
  .join("\n");

writeFileSync(target, header + body);
console.log(`baseline: ${target} from ${parts.length} files`);
