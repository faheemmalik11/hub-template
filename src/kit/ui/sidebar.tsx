/**
 * The single control on the sidebar's edge: one always-visible circular icon button that toggles
 * collapsed/expanded, plus (while expanded, on desktop) a drag-to-resize strip on the same line.
 *
 * Replaces the previous pairing of SidebarRail (an invisible full-height click-to-toggle strip)
 * with a separate resize handle placed right next to it on the same edge -- the two hit-zones
 * overlapped, so a click meant to toggle sometimes got captured by the resize handle's pointer
 * capture instead, and vice versa ("expansion not working fine"). One component now owns the
 * whole strip, and there is exactly one visible toggle affordance, never two: a filled brand-
 * coloured disc holding a chevron that points the way it moves the sidebar — right to expand
 * while collapsed, left to collapse while expanded. The fill is `bg-sidebar-primary`, which every
 * Hub already redefines through its own `--brand-*` tokens, so the button picks up each repo's
 * theme with no per-repo override. The `ring-2 ring-sidebar` is what keeps it legible as a disc
 * where it overlaps the border it sits on. Sits exactly on the header's bottom border -- the same point
 * where the sidebar's own vertical edge crosses that horizontal line -- so it reads as one badge
 * pinned to the corner, not a control floating inside either the header row or the nav list below
 * it. ShellHeader no longer renders its own SidebarTrigger for the same reason: two toggle
 * affordances stacked at that corner is what looked broken in the first place. The drag strip
 * starts below the button's clearance so dragging still works down the rest of the line -- no
 * guessing between a click and a drag on the same pixels, because they are no longer the same
 * pixels. The strip's hover highlight is the thin 2px line only, never the whole hit area, so a
 * grab target wide enough to catch easily does not look like a wide bar.
 */
const SidebarToggleHandle = React.forwardRef<HTMLDivElement, React.ComponentProps<"div">>(
  ({ className, ...props }, ref) => {
    const { state, isMobile, toggleSidebar, setWidth } = useSidebar();
    const collapsed = state === "collapsed";
    const dragging = React.useRef(false);

    if (isMobile) return null;

    // Left-side sidebar only: its own left edge sits at the window's x=0, so the pointer's own
    // clientX already is the width to apply. A right-side sidebar would need
    // window.innerWidth - clientX instead, left out until a Hub actually docks one there.
    function startDrag(event: React.PointerEvent<HTMLDivElement>) {
      dragging.current = true;
      event.currentTarget.setPointerCapture(event.pointerId);
    }
    function drag(event: React.PointerEvent<HTMLDivElement>) {
      if (!dragging.current) return;
      setWidth(event.clientX);
    }
    function endDrag(event: React.PointerEvent<HTMLDivElement>) {
      dragging.current = false;
      event.currentTarget.releasePointerCapture(event.pointerId);
    }

    // The hit area stays 16px wide so the line is easy to catch; only the 2px `after` line ever
    // takes colour, so grabbing it never paints a wide bar down the edge.
    const dragStripClass =
      "pointer-events-auto absolute inset-x-0 cursor-col-resize touch-none after:absolute after:inset-y-0 after:left-1/2 after:w-[2px] hover:after:bg-sidebar-border active:after:bg-sidebar-border";

    return (
      <div
        ref={ref}
        data-sidebar="toggle-handle"
        style={{
          // Tracks the sidebar's own edge, and the same 200ms as the frame's width transition
          // below keeps the two moving together instead of the button snapping ahead.
          left: collapsed ? "var(--sidebar-width-icon)" : "var(--sidebar-width)",
        }}
        className={cn(
          // FIXED TO THE VIEWPORT, AND RENDERED OUTSIDE <Sidebar> ON PURPOSE. The sidebar frame is
          // `fixed inset-y-0 z-10`, which is a stacking context: any child of it, at any z-index,
          // is painted below ShellHeader's sticky z-30, so this button's upper half rendered under
          // the header's translucent backdrop and it came out looking like a clipped half-disc.
          // No z-index on a child can escape that, so the handle is a sibling of the sidebar
          // instead, positioned off the same --sidebar-width var the frame uses.
          //
          // pointer-events-none is what makes the full-height box safe: it spans the whole page,
          // so it would otherwise swallow every click in a 16px column. Only the button and the
          // drag strip take pointer events back.
          "pointer-events-none fixed inset-y-0 z-40 hidden w-4 -translate-x-1/2 transition-[left] duration-200 ease-linear md:block",
          className,
        )}
        {...props}
      >
        {!collapsed && (
          <div
            role="separator"
            aria-orientation="vertical"
            aria-label="Resize sidebar"
            className={cn(dragStripClass, "top-[76px] bottom-0")}
            onPointerDown={startDrag}
            onPointerMove={drag}
            onPointerUp={endDrag}
          />
        )}
        {/* top-14 is ShellHeader's own h-14, so the button's centre lands exactly on that header's
            bottom border where it crosses the sidebar's vertical edge. */}
        <button
          type="button"
          onClick={toggleSidebar}
          aria-label={collapsed ? "Expand sidebar" : "Collapse sidebar"}
          title={collapsed ? "Expand sidebar" : "Collapse sidebar"}
          className="pointer-events-auto absolute top-14 left-1/2 z-10 flex size-6 -translate-x-1/2 -translate-y-1/2 items-center justify-center rounded-full bg-sidebar-primary text-sidebar-primary-foreground shadow-md ring-2 ring-sidebar transition-colors hover:brightness-110"
        >
          {collapsed ? (
            <ChevronRight className="size-4" strokeWidth={2.5} aria-hidden />
          ) : (
            <ChevronLeft className="size-4" strokeWidth={2.5} aria-hidden />
          )}
        </button>
      </div>
    );
  },
);
SidebarToggleHandle.displayName = "SidebarToggleHandle";

